// WCAG contrast report. Reads tokens from src/styles.css (no duplicated values).
// Usage: node scripts/contrast-report.mjs [out.md]
import { readFileSync, writeFileSync } from "node:fs";
const css = readFileSync(new URL("../src/styles.css", import.meta.url), "utf8");
const theme = css.match(/@theme\s*\{([\s\S]*?)\n\}/)[1];
const raw = {};
for (const m of theme.matchAll(/--([\w-]+):\s*([^;]+);/g)) raw[m[1]] = m[2].replace(/\s+/g, " ").trim();
const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const col = (n) => hex(raw[`color-${n}`]);
// color-mix(in srgb, var(--color-X) P%, transparent) -> {rgb, a}
const mix = (v) => { const m = v.match(/var\(--color-([\w-]+)\) ([\d.]+)%/); return { rgb: col(m[1]), a: +m[2] / 100 }; };
const over = (top, a, bot) => top.map((c, i) => c * a + bot[i] * (1 - a));
const lum = (c) => { const [r, g, b] = c.map((v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; }); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const cr = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

// Backdrops: base + worst-case mesh overlays (all mesh layers stacked at full alpha).
const meshLayers = (name) => [...raw[name].matchAll(/var\(--color-([\w-]+)\) ([\d.]+)%/g)].map((m) => ({ rgb: col(m[1]), a: +m[2] / 100 }));
const stack = (base, layers) => layers.reduce((acc, l) => over(l.rgb, l.a, acc), base);
const bone = col("bone"), carbon = col("carbon");
const backdrops = {};
for (const [n, base, mesh] of [["bone", bone, "ambient-mesh-bone"], ["carbon", carbon, "ambient-mesh-carbon"]]) {
  const L = meshLayers(mesh);
  backdrops[`${n}`] = base;
  backdrops[`${n}+mesh(max stack)`] = stack(base, L);
}
backdrops["ochre"] = col("ochre"); backdrops["sage"] = col("sage");

const glass = {};
for (const k of ["bone", "carbon", "bone-strong", "carbon-strong", "bone-solid", "carbon-solid"]) glass[k] = mix(raw[`glass-bg-${k}`]);
const solid = (g, bd) => over(g.rgb, g.a, bd);

// Text colors: [label, rgb|{rgb,a}]
const T = (n) => ({ rgb: col(n), a: 1 });
const text = {
  "carbon": T("carbon"), "graphite": T("graphite"), "brand-text": T("brand-text"), "danger-text": T("danger-text"),
  "sage-text": T("sage-text"), "warning-text": T("warning-text"), "bone": T("bone"),
  "bone@72% (jump)": { rgb: bone, a: 0.72 }, "bone@62%": { rgb: bone, a: 0.62 }, "bone@50% (min legacy)": { rgb: bone, a: 0.5 },
  "ochre": T("ochre"), "danger-on-dark": T("danger-on-dark"), "sage-on-dark": T("sage-on-dark"), "warning-on-dark": T("warning-on-dark"),
};
const rows = [];
const add = (surface, label, t, bg, level) => {
  const fg = over(t.rgb, t.a, bg); const r = cr(fg, bg);
  rows.push({ surface, label, r, level, aa: r >= 4.5, large: r >= 3 });
};
// Opaque surfaces. level: body = must pass 4.5.
const opaque = { bone, carbon, card: col("card"), "ochre-soft": col("ochre-soft"), "sage-soft": col("sage-soft"), "brick-soft": col("brick-soft"), "warning-soft": col("warning-soft") };
for (const [s, bg] of Object.entries(opaque)) {
  const light = lum(bg) > 0.3;
  // Semantic pairs only: a *-text tone is paired with its own soft fill, bone and card.
  const own = { "ochre-soft": ["brand-text"], "sage-soft": ["sage-text"], "brick-soft": ["danger-text"], "warning-soft": ["warning-text"] }[s];
  const set = light ? ["carbon", "graphite", ...(own ?? ["brand-text", "danger-text", "sage-text", "warning-text"])] : ["bone", "bone@72% (jump)", "bone@62%", "bone@50% (min legacy)", "ochre", "danger-on-dark", "sage-on-dark", "warning-on-dark"];
  for (const t of set) add(s, t, text[t], bg, "body");
}
add("ochre (button)", "carbon", text.carbon, col("ochre"), "body");
// Glass over each backdrop. tone-matched => body (must pass); mismatched => info.
const lightText = ["carbon", "graphite", "brand-text"], darkText = ["bone", "bone@72% (jump)", "bone@62%", "ochre", "danger-on-dark", "sage-on-dark", "warning-on-dark"];
for (const g of Object.keys(glass)) {
  const isLight = g.startsWith("bone");
  for (const [bn, bd] of Object.entries(backdrops)) {
    const bg = solid(glass[g], bd);
    const matched = isLight ? bn.startsWith("bone") : bn.startsWith("carbon");
    const mismatchedTransient = !matched;
    for (const t of isLight ? lightText : darkText) {
      if (bn === "ochre" || bn === "sage") { if (g.includes("solid") || g.includes("strong")) continue; }
      add(`glass-${g} over ${bn}`, t, text[t], bg, mismatchedTransient ? "info (tone mismatch / saturated backdrop)" : "body");
    }
  }
}
const f = (n) => n.toFixed(2);
let md = `# Contrast report (generated by scripts/contrast-report.mjs)\n\nSource: src/styles.css tokens. Backdrops: base + all mesh layers stacked at full alpha (worst case).\n"body" rows must pass AA 4.5; "transient" rows are tone-mismatch moments (info only).\n\n| Surface | Text | Ratio | AA 4.5 | Large 3.0 | Class |\n|---|---|---|---|---|---|\n`;
for (const r of rows) md += `| ${r.surface} | ${r.label} | ${f(r.r)} | ${r.aa ? "pass" : "FAIL"} | ${r.large ? "pass" : "FAIL"} | ${r.level} |\n`;
const bodyFails = rows.filter((r) => r.level === "body" && !r.aa);
md += `\n**Body-text AA failures: ${bodyFails.length}**\n` + bodyFails.map((r) => `- ${r.surface} / ${r.label}: ${f(r.r)}`).join("\n") + "\n";
writeFileSync(process.argv[2] ?? "/root/MetricMotive-v2-recon/qa/p3/contrast-report.md", md);
console.log(`rows=${rows.length} bodyFails=${bodyFails.length}`);
for (const r of bodyFails) console.log(`FAIL ${r.surface} | ${r.label} | ${f(r.r)}`);
