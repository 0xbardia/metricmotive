#!/usr/bin/env node
/**
 * D1 verification (read-only view calls; no account, no transaction).
 *   node scripts/verify-d1.mjs          compare src/lib/d1/guard-1.snapshot.ts with the live chain; exit 1 on any difference
 *   node scripts/verify-d1.mjs --write  regenerate the snapshot from the chain (review the diff before committing)
 */
import { createClient } from "genlayer-js";
import { studioDevnet } from "genlayer-js/chains";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const CONTRACT = "0x4105A7ccAef5072eb5A3A3C9142CD28F52c38703";
const FILE = fileURLToPath(new URL("../src/lib/d1/guard-1.snapshot.ts", import.meta.url));
const FIELDS = ["id", "owner", "version", "parent_id", "status", "status_code", "verdict", "verdict_code", "primary_pattern", "motive", "metric", "guardrails_json", "evidence_json", "findings_json", "definition_hash", "evidence_hash", "created_at", "armed_at", "evidence_at", "resolved_at"];
const plain = (v) => JSON.parse(JSON.stringify(v, (_, x) => (typeof x === "bigint" ? x.toString() : x instanceof Map ? Object.fromEntries(x) : x)));

const client = createClient({ chain: studioDevnet });
const live = plain(await client.readContract({ address: CONTRACT, functionName: "get_guard", args: [1n] }));
if (!live.found) { console.error("get_guard(1) not found on chain"); process.exit(1); }
const liveGuard = Object.fromEntries(FIELDS.map((k) => [k, live[k]]));

if (process.argv.includes("--write")) {
  const snap = { source: "GenLayer Studio Dev (chain 61997), read-only view calls", contract: CONTRACT, fetchedAt: new Date().toISOString(), guard: liveGuard };
  writeFileSync(FILE, `// GENERATED by scripts/verify-d1.mjs --write from read-only view calls (get_guard #1). Do not edit by hand.\n// Re-check against the live chain with: node scripts/verify-d1.mjs\nexport const GUARD_1_SNAPSHOT = ${JSON.stringify(snap, null, 2)} as const;\n`);
  console.log("snapshot written");
  process.exit(0);
}
const text = readFileSync(FILE, "utf8");
const snap = JSON.parse(text.slice(text.indexOf("{", text.indexOf("GUARD_1_SNAPSHOT")), text.lastIndexOf("} as const;") + 1));
const diffs = FIELDS.filter((k) => String(snap.guard[k]) !== String(liveGuard[k]));
if (snap.contract.toLowerCase() !== CONTRACT.toLowerCase()) diffs.push("contract");
if (diffs.length) { console.error("D1 snapshot DIFFERS from chain:", diffs.join(", ")); process.exit(1); }
console.log(`D1 verified against chain: Guard #${liveGuard.id} ${liveGuard.verdict} / ${liveGuard.primary_pattern}, ${FIELDS.length} fields identical`);
